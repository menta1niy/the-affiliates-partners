def translate(statement):
    if "SET next_id=MAX(next_id,?)" in statement:
        statement = statement.replace("SET next_id=MAX(next_id,?)", "SET next_id=GREATEST(next_id,?)")
    ignored = statement.lstrip().upper().startswith("INSERT OR IGNORE INTO ")
    if ignored:
        statement = statement.replace("INSERT OR IGNORE INTO", "INSERT INTO", 1)
    # Parameter markers are substituted only outside SQL string literals.
    pieces, quoted, i = [], False, 0
    while i < len(statement):
        char = statement[i]
        if char == "'":
            if quoted and i + 1 < len(statement) and statement[i + 1] == "'":
                pieces.append("''")
                i += 2
                continue
            quoted = not quoted
        pieces.append("%s" if char == "?" and not quoted else char)
        i += 1
    if quoted:
        raise ValueError("Unterminated SQL literal")
    statement = "".join(pieces)
    if ignored:
        statement = statement.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    if statement.strip().upper() == "SELECT LAST_INSERT_ROWID()":
        return "SELECT currval(pg_get_serial_sequence('audit','id'))"
    return statement


class Connection:
    def __init__(self, raw):
        self.raw = raw

    def execute(self, statement, params=()):
        return Cursor(self.raw.execute(translate(statement), params))

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


class Row:
    """Keep sqlite3.Row's index/key iteration semantics for existing db.py."""
    def __init__(self, values):
        self.values = values

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values.values())[key]
        return self.values[key]

    def keys(self):
        return self.values.keys()

    def __iter__(self):
        return iter(self.values.values())


class Cursor:
    def __init__(self, raw):
        self.raw = raw

    @property
    def rowcount(self):
        return self.raw.rowcount

    def fetchone(self):
        item = self.raw.fetchone()
        return Row(item) if item is not None else None

    def fetchall(self):
        return [Row(item) for item in self.raw.fetchall()]


def connect(url):
    import psycopg
    from psycopg.rows import dict_row
    return Connection(psycopg.connect(url, row_factory=dict_row))


def initialize(url):
    with connect(url).raw as conn:
        conn.execute("SELECT pg_advisory_xact_lock(601721408157)")
        conn.execute(SCHEMA)
        # Existing PostgreSQL deployments gain nullable columns non-destructively.
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS introduced_by_id BIGINT REFERENCES users(id)")
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS internal_id BIGINT")
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS source TEXT")
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS consent_at BIGINT")
        conn.execute("ALTER TABLE invitations ADD COLUMN IF NOT EXISTS candidate_label TEXT NOT NULL DEFAULT ''")
        conn.execute("INSERT INTO internal_id_sequence(singleton,next_id) VALUES(1,100) ON CONFLICT DO NOTHING")
        conn.execute("UPDATE internal_id_sequence SET next_id=GREATEST(next_id,COALESCE((SELECT MAX(internal_id)+1 FROM users),100)) WHERE singleton=1")
        missing = conn.execute("SELECT id FROM users WHERE internal_id IS NULL ORDER BY CASE WHEN role='owner' THEN 0 ELSE 1 END,registered_at,id").fetchall()
        for row in missing:
            number = conn.execute("UPDATE internal_id_sequence SET next_id=next_id+1 WHERE singleton=1 RETURNING next_id-1 AS allocated").fetchone()["allocated"]
            conn.execute("UPDATE users SET internal_id=%s WHERE id=%s", (number,row["id"]))
